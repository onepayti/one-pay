<script>
  document.addEventListener('DOMContentLoaded', () => {
    const form = document.querySelector('#licenciado-form');
    if (!form) {
      return;
    }

    const feedback = form.querySelector('.licenciado-form__feedback');
    const submitBtn = form.querySelector('button[type="submit"]');
    const originalBtnText = submitBtn ? submitBtn.textContent : '';

    const setFeedback = (type, message) => {
      if (!feedback) {
        return;
      }

      feedback.textContent = message;
      feedback.hidden = !message;

      feedback.classList.remove('licenciado-form__feedback--success', 'licenciado-form__feedback--error');
      if (message && type) {
        feedback.classList.add(`licenciado-form__feedback--${type}`);
      }
    };

    form.addEventListener('submit', async (event) => {
      event.preventDefault();
      if (!submitBtn) {
        return;
      }

      setFeedback('', '');

      if (!form.reportValidity()) {
        return;
      }

      submitBtn.disabled = true;
      submitBtn.textContent = 'Enviando...';

      try {
        const formData = new FormData(form);
        const response = await fetch(form.action, {
          method: 'POST',
          body: formData,
          headers: {
            'X-Requested-With': 'XMLHttpRequest',
          },
        });

        const data = await response.json();

        if (!response.ok || !data.success) {
          const message = data?.message ?? 'Não foi possível enviar sua solicitação. Tente novamente.';
          setFeedback('error', message);
          return;
        }

        setFeedback('success', data.message ?? 'Solicitação enviada com sucesso!');
        form.reset();
      } catch (error) {
        setFeedback('error', 'Ocorreram instabilidades ao enviar o formulário. Tente novamente em instantes.');
      } finally {
        submitBtn.disabled = false;
        submitBtn.textContent = originalBtnText;
      }
    });
  });
</script>

<script>
  document.addEventListener('DOMContentLoaded', () => {
    document.querySelectorAll('.card-wrap').forEach(wrap => {
      const btn = wrap.querySelector('.descollapse');
      const panel = wrap.querySelector('.collapse');
      if (!btn || !panel) return;

      panel.setAttribute('aria-hidden', 'true');
      btn.setAttribute('aria-expanded', 'false');

      btn.addEventListener('click', () => {
        const opened = wrap.classList.toggle('is-open');
        panel.setAttribute('aria-hidden', String(!opened));
        btn.setAttribute('aria-expanded', String(opened));
        btn.textContent = opened ? 'Ver menos' : 'Ver mais';
      });
    });
  });
</script>

