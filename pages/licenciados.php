<script>
  // Permite várias listas .etapa na mesma página
  document.querySelectorAll('ul.etapa').forEach(initEtapas);

  function initEtapas(ul) {
    const steps = [...ul.querySelectorAll('li')];

    // garante que a primeira esteja sempre acesa
    steps.forEach((li, i) => li.classList.toggle('on', i === 0));

    function update() {
      const gatilho = window.innerHeight * 0.45; // ajuste fino do ponto de ativação
      let ultimoIndexAceso = 0; // pelo menos a primeira fica acesa

      steps.forEach((li, i) => {
        const { top } = li.getBoundingClientRect();
        if (top < gatilho) ultimoIndexAceso = i;
      });

      steps.forEach((li, i) => {
        li.classList.toggle('on', i <= ultimoIndexAceso);
      });
    }

    // atualiza ao carregar e durante o scroll
    update();
    window.addEventListener('scroll', update, { passive: true });
    window.addEventListener('resize', update);
  }
</script>
